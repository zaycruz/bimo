//! Render an agent's iron-proxy 0.52 configuration from its spec.
//!
//! - Every listener binds to the driver-chosen host; only the tunnel listener
//!   (HTTP proxy, CONNECT, SOCKS5) is used by the agent. DNS is disabled.
//! - The allowlist is the spec's `egress.allow`; everything else is refused
//!   with 403 and an audit record carrying `rejected_by`.
//! - Each secret is read from its own file, so rotation is a file rewrite and
//!   a reload. Its placeholder is swapped in any header, and only on requests
//!   to the secret's declared hosts.
use super::{ProxyPlan, ProxyPorts};

fn quote(value: &str) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "\"\"".to_owned())
}

pub fn render(plan: &ProxyPlan, bind_host: &str, ports: ProxyPorts) -> String {
    let spec = &plan.spec;
    let mut domains = Vec::new();
    let mut cidrs = Vec::new();
    for entry in &spec.egress.allow {
        if entry.parse::<std::net::Ipv4Addr>().is_ok() {
            cidrs.push(format!("{entry}/32"));
        } else {
            domains.push(entry.clone());
        }
    }
    let list = |items: &[String]| {
        format!(
            "[{}]",
            items.iter().map(|i| quote(i)).collect::<Vec<_>>().join(", ")
        )
    };
    let mut out = String::new();
    out.push_str("# Generated by Monolith for one agent generation. Do not edit.\n");
    out.push_str("dns:\n  enabled: false\n");
    out.push_str("proxy:\n");
    // iron-proxy defaults the transparent listeners to :80 and :443 on every
    // interface; pin them to the bind host.
    for (key, port) in [
        ("http_listen", ports.http),
        ("https_listen", ports.https),
        ("tunnel_listen", ports.tunnel),
    ] {
        out.push_str(&format!("  {key}: {}\n", quote(&format!("{bind_host}:{port}"))));
    }
    if let Some(cidrs) = &plan.upstream_deny_cidrs {
        out.push_str(&format!("  upstream_deny_cidrs: {}\n", list(cidrs)));
    }
    out.push_str("tls:\n");
    out.push_str(&format!(
        "  ca_cert: {}\n  ca_key: {}\n",
        quote(&plan.dir.join("ca.crt").to_string_lossy()),
        quote(&plan.dir.join("ca.key").to_string_lossy())
    ));
    out.push_str("transforms:\n");
    out.push_str("  - name: allowlist\n    config:\n");
    out.push_str(&format!("      domains: {}\n", list(&domains)));
    out.push_str(&format!("      cidrs: {}\n", list(&cidrs)));
    if !spec.secrets.is_empty() {
        out.push_str("  - name: secrets\n    config:\n      secrets:\n");
        for secret in &spec.secrets {
            let placeholder = plan
                .placeholders
                .get(&secret.env)
                .cloned()
                .unwrap_or_default();
            out.push_str(&format!(
                "        - source: {{type: file, path: {}}}\n",
                quote(&plan.secret_file(&secret.env).to_string_lossy())
            ));
            out.push_str("          replace:\n");
            out.push_str(&format!("            proxy_value: {}\n", quote(&placeholder)));
            out.push_str("            match_headers: []\n");
            out.push_str("          rules:\n");
            for host in &secret.hosts {
                if host.parse::<std::net::Ipv4Addr>().is_ok() {
                    out.push_str(&format!("            - cidr: {}\n", quote(&format!("{host}/32"))));
                } else {
                    out.push_str(&format!("            - host: {}\n", quote(host)));
                }
            }
        }
    }
    out.push_str("management:\n");
    out.push_str(&format!(
        "  listen: {}\n  api_key_env: IRON_MANAGEMENT_API_KEY\n",
        quote(&format!("{bind_host}:{}", ports.management))
    ));
    out.push_str("metrics:\n");
    out.push_str(&format!(
        "  listen: {}\n",
        quote(&format!("{bind_host}:{}", ports.metrics))
    ));
    out.push_str("log:\n  level: info\n");
    out
}
